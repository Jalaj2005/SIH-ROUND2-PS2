"""Mock providers. No network, no key, no cost.

* ScriptedProvider  – tests: returns queued raw strings / raises queued exceptions, records calls.
* FixtureProvider   – local development (AI_PROVIDER=mock): deterministic, schema-valid output built
                      from the request/evidence found in the prompt's untrusted data block.
"""
from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel

from app.schemas.aar import GeneratedAAR
from app.schemas.scenario import GeneratedScenario
from app.services.ai.sanitize import extract_untrusted_blocks


class ScriptedProvider:
    name = "mock"

    def __init__(self, responses: list[str | Exception | dict | BaseModel] | None = None, model_name: str = "mock-model"):
        self.model_name = model_name
        self._queue = list(responses or [])
        self.calls: list[dict[str, Any]] = []

    def queue(self, *items):
        self._queue.extend(items)

    def generate_json(self, *, system_instruction: str, user_prompt: str, response_model: type[BaseModel]) -> str:
        self.calls.append({"system": system_instruction, "prompt": user_prompt, "model": response_model})
        if not self._queue:
            raise AssertionError("ScriptedProvider queue exhausted")
        item = self._queue.pop(0)
        if isinstance(item, Exception):
            raise item
        if isinstance(item, BaseModel):
            return item.model_dump_json()
        if isinstance(item, dict):
            return json.dumps(item)
        return item


class FixtureProvider:
    name = "mock"
    model_name = "fixture-provider"

    def generate_json(self, *, system_instruction: str, user_prompt: str, response_model: type[BaseModel]) -> str:
        blocks = extract_untrusted_blocks(user_prompt)
        if response_model is GeneratedScenario:
            return json.dumps(self._scenario(blocks))
        if response_model is GeneratedAAR:
            return json.dumps(self._aar(blocks[0]["evidence_package"]))
        raise ValueError("FixtureProvider does not support this response model")

    # -- scenario ---------------------------------------------------------
    def _scenario(self, blocks: list[Any]) -> dict[str, Any]:
        req = blocks[0]["requirements"]
        if len(blocks) > 1 and "previous_draft" in blocks[1]:
            prev = dict(blocks[1]["previous_draft"])
            for k in ("id", "status", "schema_version"):
                prev.pop(k, None)
            prev["instructor_notes"] = list(prev.get("instructor_notes", [])) + ["Revised from instructor feedback (fixture)."]
            return prev
        roles = req["role_ids"]
        limit = req["duration_minutes"] * 60
        fails = req["communication_failures"]
        events = [{
            "event_key": f"event-{i+1:03d}",
            "offset_seconds": int(limit * 0.15 * (i + 1)),
            "event_type": "communication_failure",
            "config": {"failure_type": ft, "duration_seconds": 60, "target_roles": [roles[i % len(roles)]],
                       "target_channel": "team_reports"},
            "description": f"Simulated {ft.replace('_', ' ')} (fictional)",
        } for i, ft in enumerate(fails)]
        decisions = [{
            "decision_key": f"decision-{i+1:03d}",
            "offset_seconds": int(limit * (0.5 + 0.25 * i)),
            "prompt": f"Fictional decision point {i+1}: choose the most appropriate next step.",
            "visible_to_roles": [roles[0]],
            "options": [{"option_id": "A", "label": "Request confirmation"}, {"option_id": "B", "label": "Proceed on current information"}],
            "rationale_required": True,
            "evaluation_criteria": [{
                "criterion_id": "information_awareness", "description": "Uses available evidence appropriately",
                "weight": 1.0, "acceptable_option_ids": ["A"],
                "scoring_notes": "Depends on the information available at decision time.",
            }],
        } for i in range(2)]
        return {
            "title": f"Fixture scenario ({req['domain']})",
            "description": "Fictional training scenario generated by the offline fixture provider.",
            "domain": req["domain"],
            "learning_objectives": req["learning_objectives"],
            "difficulty": req["difficulty"],
            "duration_minutes": req["duration_minutes"],
            "roles": [{"role_id": r, "display_name": r.replace("_", " ").title(),
                       "permissions": ["send_team_message"] + (["submit_team_decision"] if i == 0 else []),
                       "briefing": f"Fictional briefing for {r}."} for i, r in enumerate(roles)],
            "initial_reports": [{"report_id": "report-001", "title": "Initial status", "content": "Fictional status report.",
                                 "visible_to_roles": roles, "source_label": "training_simulation"}],
            "events": events,
            "decision_points": decisions,
            "instructor_notes": ["Review role visibility before approval."],
        }

    # -- AAR --------------------------------------------------------------
    def _aar(self, ev: dict[str, Any]) -> dict[str, Any]:
        events = [e["event_id"] for e in ev.get("events", [])]
        decisions = [d["decision_id"] for d in ev.get("decisions", [])]
        metric_keys = list(ev.get("metrics", {}).keys())
        anchor = (events[:1] + decisions[:1] + metric_keys[:1])
        objective = (ev.get("scenario", {}).get("learning_objectives") or ["general"])[0]
        obs = []
        if events:
            obs.append({"observation": "The event log records simulated communication degradation during the exercise.",
                        "classification": "fact", "evidence_refs": events[:1], "confidence": "high"})
        if decisions:
            obs.append({"observation": "At least one decision was submitted with a recorded rationale.",
                        "classification": "fact", "evidence_refs": decisions[:1], "confidence": "high"})
        obs.append({"observation": "Decisions may reflect how the team handled incomplete information.",
                    "classification": "interpretation", "evidence_refs": anchor[:1], "confidence": "low"})
        return {
            "title": "After-Action Review (fixture draft)",
            "executive_summary": "Draft summary generated offline from the supplied evidence package.",
            "key_observations": obs,
            "strengths": [{"text": "A decision with rationale was recorded.", "evidence_refs": (decisions or events or metric_keys)[:1]}],
            "improvement_areas": [{"text": "Review how delayed or dropped reports were acknowledged.", "evidence_refs": (events or decisions or metric_keys)[:1]}],
            "recommendations": [{"text": "Practise explicit acknowledgement of delayed reports.", "related_learning_objective": objective}],
            "evidence_limitations": ["Offline fixture output; not a real model analysis."],
            "follow_up_scenario_brief": "Follow-up exercise emphasising confirmation of critical updates.",
        }
